package Java.Examples;

public class BinaryDemo {
    public static void main(String[] args) {
        int a = 1;
        int b = 2;
        int c = 3;
        int d = 4;
        int e = 5;
        int f = 6;
        int g = 7;
        int h = 8;
        int i = 9;     // 15
                       // 8  4  2  1
                       // 1  1  1   1
        int j = 10;
        int k = 11;
        int l = 12;
        int m = 13;
        int n = 14;
        int p = 15;
        int q = 16;

        System.out.println("a = " + a + " -> " + Integer.toBinaryString(a));
        System.out.println("b = " + b + " -> " + Integer.toBinaryString(b));
        System.out.println("c = " + c + " -> " + Integer.toBinaryString(c));
        System.out.println("d = " + d + " -> " + Integer.toBinaryString(d));
        System.out.println("e = " + e + " -> " + Integer.toBinaryString(e));
        System.out.println("f = " + f + " -> " + Integer.toBinaryString(f));
        System.out.println("g = " + g + " -> " + Integer.toBinaryString(g));
        System.out.println("h = " + h + " -> " + Integer.toBinaryString(h));
        System.out.println("i = " + i + " -> " + Integer.toBinaryString(i));
        System.out.println("j = " + j + " -> " + Integer.toBinaryString(j));
        System.out.println("k = " + k + " -> " + Integer.toBinaryString(k));
        System.out.println("l = " + l + " -> " + Integer.toBinaryString(l));
        System.out.println("m = " + m + " -> " + Integer.toBinaryString(m));
        System.out.println("n = " + n + " -> " + Integer.toBinaryString(n));
        System.out.println("p = " + p + " -> " + Integer.toBinaryString(p));
        System.out.println("q = " + q + " -> " + Integer.toBinaryString(q));
    }
}
//       128, 64, 32, 16, 8, 4, 2, 1
// 255 =  1   1    1   1  1  1  1  1